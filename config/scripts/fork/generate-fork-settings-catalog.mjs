#!/usr/bin/env node
// Fork settings catalog (FORK.md): writes src/shared/fork/settings-catalog/*.generated.ts, one
// row per key of the `GlobalSettings` type (value type, description, area), which
// `orca settings` reads. Run it after adding, renaming or removing a setting:
//   pnpm run generate:fork-settings-catalog
// `--check` writes nothing and exits 1 when the committed files are out of date.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { AREAS, DESCRIPTIONS, areaOf } from './settings-catalog-rules.mjs'
import { readSettingsKeys } from './settings-catalog-type-reader.mjs'

const repoRoot = path.resolve(import.meta.dirname, '..', '..', '..')
const outDir = path.join(repoRoot, 'src', 'shared', 'fork', 'settings-catalog')
const INDEX_FILE = 'settings-catalog-rows.generated.ts'
const HEADER = [
  '// Generated by config/scripts/fork/generate-fork-settings-catalog.mjs from the GlobalSettings',
  '// type. Do not edit: run `pnpm run generate:fork-settings-catalog`.'
]
/** A value type longer than this is described less deeply; the app still normalizes the rest. */
const SHAPE_BUDGET = 1200
/** A record names its keys only when the list is short. */
const MAX_NAMED_KEYS = 12
/** The formatter's print width. */
const LINE_WIDTH = 100

function prune(shape, depth) {
  const next = { ...shape }
  if (next.k === 'record' && next.keys && next.keys.length > MAX_NAMED_KEYS) {
    delete next.keys
  }
  if (next.k === 'object') {
    if (depth <= 0) {
      const { nullable, optional } = next
      return { k: 'unknown', ...(nullable ? { nullable } : {}), ...(optional ? { optional } : {}) }
    }
    next.fields = Object.fromEntries(
      Object.entries(next.fields).map(([name, field]) => [name, prune(field, depth - 1)])
    )
  } else if (next.k === 'array' || next.k === 'record') {
    next.of = prune(next.of, depth - 1)
  } else if (next.k === 'union') {
    next.of = next.of.map((member) => prune(member, depth))
  }
  return next
}

function fitShape(shape) {
  for (let depth = 4; depth >= 0; depth -= 1) {
    const fitted = prune(shape, depth)
    if (JSON.stringify(fitted).length <= SHAPE_BUDGET) {
      return fitted
    }
  }
  return { k: 'unknown' }
}

function constName(areaId) {
  return `FORK_SETTINGS_ROWS_${areaId.toUpperCase().replace(/-/g, '_')}`
}

function fileName(areaId) {
  return `settings-rows-${areaId}.generated.ts`
}

/** A single-quoted TypeScript string literal, as the formatter prints it. */
function quote(text) {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function buildFiles() {
  const keys = readSettingsKeys(repoRoot)
  const stale = Object.keys(DESCRIPTIONS).filter((name) => !keys.some((key) => key.key === name))
  if (stale.length > 0) {
    throw new Error(`settings-catalog-rules.mjs describes keys that no longer exist: ${stale}`)
  }
  const files = new Map()
  const used = []
  for (const area of AREAS) {
    const rows = keys.filter((key) => areaOf(key.key) === area.id)
    if (rows.length === 0) {
      continue
    }
    used.push(area)
    const lines = [...HEADER, `export const ${constName(area.id)} = {`]
    rows.forEach((row, index) => {
      // The hand-written line wins: it is there because the doc comment did not suit a reader.
      const description = DESCRIPTIONS[row.key] ?? row.doc
      if (!description) {
        throw new Error(
          `Setting "${row.key}" has no doc comment. Add one to its type, or a line to DESCRIPTIONS in config/scripts/fork/settings-catalog-rules.mjs.`
        )
      }
      const json = JSON.stringify({
        t: fitShape(row.shape),
        d: description,
        ...(row.optional ? { o: true } : {})
      })
      const comma = index === rows.length - 1 ? '' : ','
      const oneLine = `  ${row.key}: ${quote(json)}${comma}`
      // The formatter moves a value that does not fit the line under its key.
      lines.push(
        oneLine.length <= LINE_WIDTH ? oneLine : `  ${row.key}:\n    ${quote(json)}${comma}`
      )
    })
    lines.push('}', '')
    files.set(fileName(area.id), lines.join('\n'))
  }
  const index = [
    ...HEADER,
    ...used.map(
      (area) =>
        `import { ${constName(area.id)} } from './${fileName(area.id).replace(/\.ts$/, '')}'`
    ),
    '',
    '/** Every settings key by area, in the order the CLI shows them. */',
    'export const FORK_SETTINGS_AREA_ROWS = [',
    ...used.flatMap((area, i) => [
      '  {',
      `    id: ${quote(area.id)},`,
      `    title: ${quote(area.title)},`,
      `    rows: ${constName(area.id)}`,
      i === used.length - 1 ? '  }' : '  },'
    ]),
    '] as const',
    ''
  ]
  files.set(INDEX_FILE, index.join('\n'))
  return files
}

function main() {
  const check = process.argv.includes('--check')
  const files = buildFiles()
  const existing = existsSync(outDir)
    ? readdirSync(outDir).filter((name) => name.endsWith('.generated.ts'))
    : []
  const outdated = [...files].filter(
    ([name, text]) =>
      !existing.includes(name) || readFileSync(path.join(outDir, name), 'utf8') !== text
  )
  const orphans = existing.filter((name) => !files.has(name))
  if (check) {
    if (outdated.length > 0 || orphans.length > 0) {
      const names = [...outdated.map(([name]) => name), ...orphans].join(', ')
      console.error(
        `The fork settings catalog is out of date (${names}). Run: pnpm run generate:fork-settings-catalog`
      )
      process.exit(1)
    }
    return
  }
  mkdirSync(outDir, { recursive: true })
  for (const [name, text] of outdated) {
    writeFileSync(path.join(outDir, name), text)
  }
  for (const name of orphans) {
    rmSync(path.join(outDir, name))
  }
  console.log(`fork settings catalog: ${files.size - 1} areas, ${outdated.length} files written`)
}

main()
